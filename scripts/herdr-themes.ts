// Writes herdr-themes.ts from the herdr source of one release: the built-in palettes, the name aliases and the dark and light siblings.
//
//   bun scripts/herdr-themes.ts v0.9.5
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const version = process.argv[2];
if (!/^v\d+\.\d+\.\d+$/.test(version ?? "")) throw new Error("usage: bun scripts/herdr-themes.ts vX.Y.Z");

const source = async (path: string) => {
  const res = await fetch(`https://raw.githubusercontent.com/herdrdev/herdr/${version}/${path}`);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return res.text();
};
const [state, config, app] = await Promise.all([source("src/app/state.rs"), source("src/config/theme.rs"), source("src/app/mod.rs")]);

// ratatui's named colors, as ANSI indexes.
const ANSI: Record<string, number> = {
  Black: 0, Red: 1, Green: 2, Yellow: 3, Blue: 4, Magenta: 5, Cyan: 6, Gray: 7,
  DarkGray: 8, LightRed: 9, LightGreen: 10, LightYellow: 11, LightBlue: 12, LightMagenta: 13, LightCyan: 14, White: 15,
};
const hex = (...c: string[]) => `#${c.map((v) => Number(v).toString(16).padStart(2, "0")).join("")}`;

function color(expr: string): string | number | null {
  const rgb = /^Color::Rgb\((\d+),\s*(\d+),\s*(\d+)\)$/.exec(expr);
  if (rgb) return hex(rgb[1], rgb[2], rgb[3]);
  if (expr === "Color::Reset") return null;
  const name = /^Color::(\w+)$/.exec(expr)?.[1];
  if (name && name in ANSI) return ANSI[name];
  throw new Error(`unknown color ${expr}`);
}

const slots = [...state.matchAll(/^\s*pub (\w+): Color,$/gm)].map((m) => m[1]);
if (slots.length < 10) throw new Error("no Palette struct found in state.rs");

const fns = new Map<string, Record<string, string | number | null>>();
for (const m of state.matchAll(/pub fn (\w+)\(\) -> Self \{\s*Self \{([^}]*)\}/g)) {
  const palette: Record<string, string | number | null> = {};
  for (const f of m[2].matchAll(/(\w+):\s*(Color::(?:Rgb\([^)]*\)|\w+)),/g)) palette[f[1]] = color(f[2].trim());
  if (slots.every((s) => s in palette)) fns.set(m[1], palette);
}

const fromName = /pub fn from_name[\s\S]*?\n {4}\}/.exec(state)?.[0] ?? "";
const themes: Record<string, Record<string, string | number | null>> = {};
for (const m of fromName.matchAll(/"([\w-]+)" => Some\(Self::(\w+)\(\)\)/g)) {
  const palette = fns.get(m[2]);
  if (!palette) throw new Error(`no palette function ${m[2]}`);
  themes[m[1]] = palette;
}

const canonical = /fn canonical_theme_name[\s\S]*?\n\}/.exec(config)?.[0] ?? "";
const aliases: Record<string, string> = {};
for (const m of canonical.matchAll(/((?:"[\w-]+"\s*\|?\s*)+)=> Some\("([\w-]+)"\)/g)) {
  for (const a of m[1].matchAll(/"([\w-]+)"/g)) aliases[a[1]] = m[2];
}

const siblingFn = /fn sibling_theme_names[\s\S]*?\n\}/.exec(app)?.[0] ?? "";
const siblings: Record<string, [string, string]> = {};
for (const m of siblingFn.matchAll(/((?:"[\w-]+"\s*\|?\s*)+)=> \{\s*\("([\w-]+)"\.to_string\(\),\s*"([\w-]+)"\.to_string\(\)\)/g)) {
  for (const a of m[1].matchAll(/"([\w-]+)"/g)) siblings[a[1]] = [m[2], m[3]];
}

if (Object.keys(themes).length < 2 || !Object.keys(aliases).length || !Object.keys(siblings).length) throw new Error("the herdr source has a new shape; update this script");

const out = `// Generated by scripts/herdr-themes.ts from herdr ${version}. Do not edit.
// A color is "#rrggbb", an ANSI index (0 to 15) of the terminal palette, or null for the terminal default.
export const HERDR_VERSION = ${JSON.stringify(version)};
export const SLOTS = ${JSON.stringify(slots)} as const;
export type Slot = (typeof SLOTS)[number];
export type HerdrColor = string | number | null;
export const THEMES: Record<string, Record<Slot, HerdrColor>> = ${JSON.stringify(themes, null, 2)};
// Other names that herdr takes for a theme.
export const ALIASES: Record<string, string> = ${JSON.stringify(aliases, null, 2)};
// The dark and light theme names that herdr uses when dark_name or light_name is not set.
export const SIBLINGS: Record<string, [string, string]> = ${JSON.stringify(siblings)};
`;
writeFileSync(join(import.meta.dir, "..", "herdr-themes.ts"), out);
console.log(`herdr-themes.ts: ${Object.keys(themes).length} themes from herdr ${version}`);
